"""# Fine tune model"""

import random
import os
from datasets import Dataset

SEED = 42
random.seed(SEED)
set_seed(SEED)
np.random.seed(SEED)
torch.manual_seed(SEED)

if torch.cuda.is_available():
    torch.cuda.manual_seed_all(SEED)

# model name
MODEL_NAME = "ProtectAI/deberta-v3-base-prompt-injection-v2"

# Data files
TRAIN_FILE = "/content/drive/MyDrive/sentinelai_train.csv"
VAL_FILE =  "/content/drive/MyDrive/sentinelai_val.csv"
TEST_FILE = "/content/drive/MyDrive/sentinelai_test.csv"

# output
OUTPUT_DIR = "/content/sentinelai_prompt_injection_model"

# Training config
MAX_LENGTH = 512
BATCH_SIZE = 8
EPOCHS = 3
LEARNING_RATE = 2e-5
WEIGHT_DECAY = 0.01

"""# load Dataset"""

train_df = pd.read_csv(TRAIN_FILE)
val_df = pd.read_csv(VAL_FILE)
test_df = pd.read_csv(TEST_FILE)

print("Train:", train_df.shape)
print("Validation:", val_df.shape)
print("Test:", test_df.shape)

"""# validate dataset"""

REQUIRE_COL = ['content', 'label']

for name, df in [('train', train_df), ('val', val_df), ('test', test_df)]:
    print(f"Validating {name} dataset...")

    missing = [col for col in REQUIRE_COL if col not in df.columns]
    if missing:
        raise ValueError(f"{name} is missing columns: {missing}")

    # missing value
    print("missing content:", df['content'].isna().sum())
    print("missing label:", df['label'].isna().sum())

    # labels
    print("labels:", sorted(df['label'].unique().tolist()))

"""# class distribution"""

def show_distribution(name,df):
    print(name)

    counts = df['label'].value_counts().sort_index()

    for label,count in counts.items():
        label_name = "BENIGN" if label == 0 else "MALICIOUS"

        percentage = 100 * count/len(df)

        print(f"{label_name}: {count} ({percentage:.2f}%)")

show_distribution("train",train_df)
show_distribution("val",val_df)
show_distribution("test",test_df)

train_dataset = Dataset.from_pandas(train_df,preserve_index= False)
val_dataset = Dataset.from_pandas(val_df,preserve_index= False)
test_dataset = Dataset.from_pandas(test_df, preserve_index= False)

print(train_dataset)
print(val_dataset)
print(test_dataset)

"""# load tokenizer"""

tokenizer = AutoTokenizer.from_pretrained(MODEL_NAME)

"""# tokenization"""

def tokenize_function(examples):
    return tokenizer(
        examples["content"],
        truncation=True,
        max_length=MAX_LENGTH
    )
train_tokenized = train_dataset.map(tokenize_function, batched=True, remove_columns=["content"])
val_tokenized = val_dataset.map(tokenize_function, batched=True, remove_columns=["content"])
test_tokenized = test_dataset.map(tokenize_function, batched=True, remove_columns=["content"])

"""# load pretrained model"""

model = AutoModelForSequenceClassification.from_pretrained(MODEL_NAME)

model.config.id2label = {0: "BENIGN", 1: "MALICIOUS"}
model.config.label2id = {"BENIGN": 0, "MALICIOUS": 1}

model.to(DEVICE)

print(model.config)

"""# Data collator"""

data_collator = DataCollatorWithPadding(tokenizer=tokenizer)

"""# metrix"""

def compute_metrics(eval_pred):
    logits,labels = eval_pred

    predictions = np.argmax(logits,axis=1)
    accuracy = accuracy_score(labels,predictions)
    precision = precision_score(labels,predictions,zero_division=0)
    recall = recall_score(labels,predictions,zero_division=0)
    f1 = f1_score(labels,predictions,zero_division=0)

    return {
        "accuracy": accuracy,
        "precision": precision,
        "recall": recall,
        "f1": f1
    }

"""# Training config"""

training_args = TrainingArguments(
    output_dir=OUTPUT_DIR,
    learning_rate=LEARNING_RATE,

    num_train_epochs=EPOCHS,
    weight_decay=WEIGHT_DECAY,

    # Batch
    per_device_train_batch_size=BATCH_SIZE,
    per_device_eval_batch_size=BATCH_SIZE,
    gradient_accumulation_steps=2,

    # Evaluation
    eval_strategy="epoch",

    save_strategy="epoch",

    logging_strategy="steps",

    logging_steps=50,

    # Best model
    load_best_model_at_end=True,

    metric_for_best_model="f1",

    greater_is_better=True,

    # GPU
    fp16=torch.cuda.is_available(),

    # Checkpoints
    save_total_limit=2,

    # Misc
    seed=SEED,

    report_to="none"
)

"""# create trainer"""

trainer = Trainer(

    model=model,

    args=training_args,

    train_dataset=train_tokenized,

    eval_dataset=val_tokenized,

    processing_class=tokenizer,

    data_collator=data_collator,

    compute_metrics=compute_metrics,

    callbacks=[
        EarlyStoppingCallback(
            early_stopping_patience=2
        )
    ]
)

"""# Fine tune"""

train_result = trainer.train()

"""# save model"""

trainer.save_model(OUTPUT_DIR)

tokenizer.save_pretrained(
    OUTPUT_DIR
)

print("Model saved to:")
print(OUTPUT_DIR)

"""# validation results"""

val_results = trainer.evaluate(
    eval_dataset=val_tokenized
)

