import numpy as np
import pandas as pd
import torch
from transformers import AutoTokenizer, AutoModelForSequenceClassification, DataCollatorWithPadding, TrainingArguments, Trainer, EarlyStoppingCallback, set_seed
from sklearn.metrics import accuracy_score, precision_score, recall_score, f1_score, confusion_matrix, classification_report

MODEL_NAME = "ProtectAI/deberta-v3-base-prompt-injection-v2"
TEST_FILE = "/content/drive/MyDrive/sentinelai_test.csv"

MAX_LENGTH = 512

DEVICE = torch.device("cuda" if torch.cuda.is_available() else "cpu")

if torch.cuda.is_available():
    print(torch.cuda.get_device_name())

test_df = pd.read_csv(TEST_FILE)

print(test_df.shape)
print(test_df.columns.to_list())
print(test_df.head())

test_df['label'].value_counts()

"""# load original pretrained model"""

tokenizer = AutoTokenizer.from_pretrained(MODEL_NAME)
model = AutoModelForSequenceClassification.from_pretrained(MODEL_NAME)

model.to(DEVICE)
model.eval()

print("original pretrained model loaded")

"""# Run predictions"""

texts = test_df['content'].tolist()
labels = test_df['label'].to_numpy()

all_probs = []
batch_size = 16

for start in range(0, len(texts), batch_size):
    batch_texts = texts[start:start+batch_size]
    inputs = tokenizer(batch_texts, return_tensors="pt", padding=True, truncation=True, max_length=MAX_LENGTH)
    inputs = {key: val.to(DEVICE) for key, val in inputs.items()}

    with torch.no_grad():
        outputs = model(**inputs)

    probabilities = torch.softmax(outputs.logits, dim=1)
    all_probs.append(probabilities.cpu().numpy())

all_probs = np.concatenate(all_probs, axis=0)
malicious_prob = all_probs[:,1]

baseline_pred = (malicious_prob >= 0.5).astype(int)

print("Predictions completed.")

"""# calculate baseline matrix"""

accuracy = accuracy_score(labels, baseline_pred)
precision = precision_score(labels, baseline_pred, zero_division=0)
recall = recall_score(labels, baseline_pred, zero_division=0)
f1 = f1_score(labels, baseline_pred, zero_division=0)
tn, fp, fn, tp = confusion_matrix(labels, baseline_pred).ravel()

false_positive_rate = fp / (fp + tn)
false_negative_rate = fn / (fn + tp)

print("="*15)
print("PRETRAIN_MODEL - BASELINE")
print("="*15)

print(f"Accuracy            : {accuracy:.4f}")
print(f"Precision           : {precision:.4f}")
print(f"Recall              : {recall:.4f}")
print(f"F1 Score            : {f1:.4f}")
print(f"False Positive Rate : {false_positive_rate:.4f}")
print(f"False Negative Rate : {false_negative_rate:.4f}")

print("\nConfusion Matrix")
print("-" * 60)

print(f"True Negative  : {tn}")

print(f"False Positive : {fp}")

print(f"False Negative : {fn}")

print(
    classification_report(
        labels,
        baseline_pred,
        target_names=[
            "Benign",
            "Malicious"
        ],
        digits=4,
        zero_division=0
    )
)

